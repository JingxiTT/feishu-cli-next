"""Keep the fork layer bounded: a fixed root, markdown-only docs, sealed evidence,
fork files named *_next.go inside upstream packages, and a recorded list of the
upstream files the fork edits.

`check` reports every violation; `seal` records new evidence files and refuses
to change a recorded one; `footprint` rewrites the edited-upstream-file list.
Upstream paths themselves are guarded by the capability gate's source inventory.
"""
import argparse
import collections
import hashlib
import json
import os
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = 'evidence/MANIFEST.sha256'
# Evidence files that describe the directory rather than record a result.
UNSEALED = (MANIFEST, 'evidence/README.md')
# Hashes of the synced upstream release; a sync moves this with the gate baseline.
UPSTREAM_SOURCES = 'baseline/v1.0.98/sources.json'
FOOTPRINT = 'docs/upstream-footprint.md'

# Upstream's root at the synced release. A sync that adds an entry extends this.
UPSTREAM_ROOT = (
    '.codecov.yml', '.gitattributes', '.github', '.gitignore', '.gitleaks.toml',
    '.gitleaksignore', '.golangci.yml', '.goreleaser.yml', '.licenserc.yaml',
    'AGENTS.md', 'CHANGELOG.md', 'LICENSE', 'Makefile', 'README.md', 'README.zh.md',
    'affordance', 'build.sh', 'cmd', 'content_embed.go', 'content_embed_affordance_test.go',
    'errs', 'events', 'extension', 'go.mod', 'go.sum', 'internal', 'isolated-skills',
    'lark_suite_assets_test.go', 'lint', 'main.go', 'main_authsidecar.go',
    'main_noauthsidecar.go', 'main_noauthsidecar_test.go', 'package-lock.json',
    'package.json', 'scripts', 'shortcuts', 'sidecar', 'skill-template', 'skills', 'tests',
)
# The fork layer. The three Go files test or feed the root-package embed, which
# go:embed pins to the repository root.
FORK_ROOT = (
    'README.upstream.md', 'SECURITY.md', 'agent-skills', 'agent_content_embed.go',
    'agent_content_embed_test.go', 'agent_skill_guidance_test.go', 'baseline', 'docs',
    'evaluation', 'evidence', 'next.mk',
)


def tracked(root):
    out = subprocess.check_output(['git', '-C', str(root), 'ls-files', '-z']).decode()
    return [name for name in out.split('\0') if name]


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def read_manifest(root):
    """Return {path: sha256}; a duplicate or malformed line is itself a violation."""
    entries, problems = {}, []
    path = root / MANIFEST
    if not path.is_file():
        return entries, [MANIFEST + ': missing']
    for number, line in enumerate(path.read_text(encoding='utf-8').splitlines(), 1):
        value, separator, name = line.partition('  ')
        if not separator or len(value) != 64 or not name or name in entries:
            problems.append('{}:{}: malformed or duplicate entry'.format(MANIFEST, number))
            continue
        entries[name] = value
    return entries, problems


def sealed_files(names):
    return sorted(n for n in names if n.startswith('evidence/') and n not in UNSEALED)


def footprint(root):
    """Pinned upstream files whose bytes differ from the synced release."""
    pinned = json.loads((root / UPSTREAM_SOURCES).read_text(encoding='utf-8'))['files']
    edited = sorted(name for name, expected in pinned.items()
                    if not (root / name).is_file() or digest(root / name) != expected)
    return edited, len(pinned), unpinned(root, pinned)


def unpinned(root, pinned):
    """Upstream root entries with no pinned hash, so their fork edits are invisible here."""
    covered = {name.split('/', 1)[0] for name in pinned}
    return [entry + '/' if (root / entry).is_dir() else entry
            for entry in UPSTREAM_ROOT if entry not in covered and (root / entry).exists()]


def render_footprint(edited, pinned, uncovered=()):
    groups = collections.defaultdict(list)
    for name in edited:
        groups[name.split('/', 1)[0] if '/' in name else '(root)'].append(name)
    lines = ['# Upstream files this fork edits', '',
             'Generated by `python3 scripts/next_layout.py footprint`; do not edit by hand.', '',
             'Each path differs from the synced upstream release recorded in',
             '`{}` and is where the next sync can conflict.'.format(UPSTREAM_SOURCES),
             'Before adding one, put the logic in a fork-owned file (`<name>_next.go`',
             'beside the upstream file, or a `next*` package) and keep the edit here to a',
             'call into it. A file restored to upstream bytes drops off this list.', '',
             '{} of {} pinned upstream files.'.format(len(edited), pinned)]
    for group in sorted(groups):
        lines += ['', '## {} ({})'.format(group, len(groups[group])), '']
        lines += ['- `{}`'.format(name) for name in groups[group]]
    if uncovered:
        lines += ['', '## Not covered', '',
                  'These upstream paths have no pinned hashes, so fork edits to them never',
                  'appear above. Compare them with the upstream release by hand during a sync.', '']
        lines += ['- `{}`'.format(name) for name in uncovered]
    return '\n'.join(lines) + '\n'


def footprint_problems(root):
    if not (root / UPSTREAM_SOURCES).is_file():
        return []
    expected = render_footprint(*footprint(root))
    path = root / FOOTPRINT
    current = path.read_text(encoding='utf-8') if path.is_file() else ''
    if current == expected:
        return []
    listed = lambda text: {line[3:-1] for line in text.partition('\n## Not covered\n')[0].splitlines()
                           if line.startswith('- `')}
    added, restored = sorted(listed(expected) - listed(current)), sorted(listed(current) - listed(expected))
    detail = '; '.join(part for part in (
        'newly edited upstream files: ' + ', '.join(added) if added else '',
        'restored to upstream: ' + ', '.join(restored) if restored else '') if part)
    return ['{}: out of date; run python3 scripts/next_layout.py footprint{}'.format(FOOTPRINT, ' (' + detail + ')' if detail else '')]


def unmarked_fork_files(root, names):
    """Fork Go files inside an upstream package must say so in their name.

    A package is upstream when the synced release pins a Go file in its
    directory. Root files are listed in FORK_ROOT instead.
    """
    if not (root / UPSTREAM_SOURCES).is_file():
        return []
    pinned = json.loads((root / UPSTREAM_SOURCES).read_text(encoding='utf-8'))['files']
    packages = {os.path.dirname(name) for name in pinned if name.endswith('.go')} - {''}
    return ['{}: fork file in upstream package; name it <name>_next.go or <name>_next_test.go'.format(name)
            for name in sorted(names)
            if name.endswith('.go') and name not in pinned and os.path.dirname(name) in packages
            and '_next' not in os.path.basename(name)]


def check(root, names=None):
    names = tracked(root) if names is None else names
    problems = []
    allowed = set(UPSTREAM_ROOT) | set(FORK_ROOT)
    for entry in sorted({name.split('/', 1)[0] for name in names} - allowed):
        problems.append('{}: new root entry; place it in an existing directory or extend the allowlist in scripts/next_layout.py'.format(entry))
    for name in sorted(n for n in names if n.startswith('docs/') and not n.endswith('.md')):
        problems.append('{}: docs/ holds markdown only; records belong in evidence/, gate inputs in baseline/'.format(name))
    entries, malformed = read_manifest(root)
    problems.extend(malformed)
    present = sealed_files(names)
    for name in present:
        if name not in entries:
            problems.append('{}: not sealed; run python3 scripts/next_layout.py seal'.format(name))
        elif not (root / name).is_file() or digest(root / name) != entries[name]:
            problems.append('{}: sealed evidence changed; add a new file instead of editing a record'.format(name))
    for name in sorted(set(entries) - set(present)):
        problems.append('{}: sealed evidence removed or renamed'.format(name))
    problems.extend(footprint_problems(root))
    problems.extend(unmarked_fork_files(root, names))
    return problems


def seal(root, names=None):
    """Append unsealed evidence files; never rewrite an existing entry."""
    names = tracked(root) if names is None else names
    entries, malformed = read_manifest(root) if (root / MANIFEST).is_file() else ({}, [])
    if malformed:
        raise ValueError('; '.join(malformed))
    added = [name for name in sealed_files(names) if name not in entries]
    (root / MANIFEST).parent.mkdir(parents=True, exist_ok=True)
    with (root / MANIFEST).open('a', encoding='utf-8', newline='\n') as stream:
        for name in added:
            stream.write('{}  {}\n'.format(digest(root / name), name))
    return added


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('action', choices=('check', 'seal', 'footprint'))
    parser.add_argument('--target', type=Path, default=ROOT)
    args = parser.parse_args(argv)
    root = args.target.resolve()
    if args.action == 'seal':
        try:
            added = seal(root)
        except ValueError as error:
            print(error, file=sys.stderr)
            return 2
        print('sealed {} new evidence file(s)'.format(len(added)))
    if args.action == 'footprint':
        edited, pinned, uncovered = footprint(root)
        (root / FOOTPRINT).write_text(render_footprint(edited, pinned, uncovered), encoding='utf-8', newline='\n')
        print('{} of {} pinned upstream files edited'.format(len(edited), pinned))
    problems = check(root)
    for problem in problems:
        print(problem, file=sys.stderr)
    return 1 if problems else 0


if __name__ == '__main__':
    sys.exit(main())
