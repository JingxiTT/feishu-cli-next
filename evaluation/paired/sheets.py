"""Fresh paired task: native raw values and formula metadata are separate reads.

Live evidence: docs/sections/sheets-private-live-evidence.json. The historical
scenario is reused for resource selection, metadata and artifact validation;
its render behavior and coverage-only proof are not reused. Omitted/default
rendering is explicitly unsupported because it was not observed live. Documented
sheet-structure and CSV inspection are also classified as unsupported strategies
after bounded selector validation; their native output is not emulated here.
"""
from copy import deepcopy
import hashlib
import json
from pathlib import Path

from scenarios import sheets as original

SCENARIO = "paired-sheets"
SOURCE = deepcopy(original.SOURCE)
BINDING = deepcopy(original.BINDING)
READ_PATH = original.READ_PATH
COORDS = original.COORDS
TASK = deepcopy(original.TASK)
TASK.update(id="paired-sheets", section="sheets")
TASK["prompt"] += " Preserve the formula cell's numeric result alongside its explicit formula field."
TASK["fixture"].update(scenario=SCENARIO, scenario_section=SCENARIO)
# Separately declared wire observations for the verifier, not generated by the
# adapter's rendering function. Expected content stays outside the public task.
TASK["expected"]["rendered"] = {
    "raw_value": {"A1": {"value": 0}, "B1": {"value": False}, "C1": {"value": ""},
                  "D1": {"value": "你好"}, "E1": {"value": 1}},
    "formula": {"A1": {"value": "0"}, "B1": {"value": "FALSE"}, "C1": {},
                "D1": {"value": "你好"}, "E1": {"formula": "=A1+1", "value": 1}},
}


def _content_hash(cell):
    content = {key: cell[key] for key in ("value", "formula") if key in cell}
    return hashlib.sha256(json.dumps(content, ensure_ascii=False, sort_keys=True,
                                    separators=(",", ":"), allow_nan=False).encode()).hexdigest()


def _render(cell, mode):
    cell = deepcopy(cell)
    if mode == "raw_value":
        cell.pop("formula", None)
    elif "formula" not in cell:
        value = cell.get("value")
        if value == "" or value is None:
            cell.pop("value", None)
        elif type(value) is bool:
            cell["value"] = "TRUE" if value else "FALSE"
        elif type(value) in (int, float):
            cell["value"] = str(value)
    # Formula rendering retains the explicit formula and numeric result/cache.
    return cell


class Scenario(original.Scenario):
    def dispatch(self, method, uri, body_bytes, headers):
        try:
            return super().dispatch(method, uri, body_bytes, headers)
        except ValueError as error:
            if str(error) != "unsupported read tool":
                raise
            # The parent already checked signed-target identity, method/path,
            # encoded body and workbook. Distinguish a documented unmodeled
            # strategy from an invalid operation without inventing its output.
            body = original._json(body_bytes)
            tool, data = body["tool_name"], original._json(body["input"])
            if tool not in ("get_sheet_structure", "get_range_as_csv"):
                raise
            selectors = set(data) & {"sheet_id", "sheet_name"}
            if not selectors or data.get("sheet_id", SOURCE["sheet_id"]) != SOURCE["sheet_id"] or data.get("sheet_name", "Fixture") != "Fixture":
                raise ValueError("foreign or missing sheet selector") from error
            optional = {"range", "info_type"} if tool == "get_sheet_structure" else {"range", "max_rows", "max_chars", "skip_hidden"}
            if set(data) - ({"excel_id", "sheet_id", "sheet_name"} | optional):
                raise ValueError("unknown inspection input") from error
            if "range" in data and data["range"] not in ("A:ZZZ", "A:E"):
                original._columns(data["range"])
            if tool == "get_sheet_structure" and data.get("info_type", "all") not in ("all", "merged_cells_infos", "row_heights_column_widths", "hidden_infos", "group_infos"):
                raise ValueError("invalid structure category") from error
            if "skip_hidden" in data and type(data["skip_hidden"]) is not bool:
                raise ValueError("boolean switch required") from error
            for flag in ("max_rows", "max_chars"):
                if flag in data and (type(data[flag]) is not int or data[flag] < 1):
                    raise ValueError("positive integer limit required") from error
            raise ValueError("unsupported strategy: documented Sheets inspection is outside this paired native fixture") from error

    def _cells(self, data):
        allowed = {"excel_id", "sheet_id", "sheet_name", "ranges", "value_render_option",
                   "include_styles", "include_truncation_info", "include_conditional_format_style",
                   "skip_hidden", "cell_limit", "max_chars"}
        if set(data) - allowed:
            raise ValueError("unknown cell input")
        selectors = set(data) & {"sheet_id", "sheet_name"}
        if not selectors or data.get("sheet_id", SOURCE["sheet_id"]) != SOURCE["sheet_id"] or data.get("sheet_name", "Fixture") != "Fixture":
            raise ValueError("foreign or missing sheet selector")
        mode = data.get("value_render_option")
        if (mode is None and "value_render_option" not in data) or mode == "formatted_value":
            raise ValueError("unsupported strategy: default/formatted native rendering has no observed fixture contract")
        if type(mode) is not str or mode not in ("raw_value", "formula"):
            raise ValueError("invalid rendering")
        for flag in ("include_styles", "include_truncation_info", "include_conditional_format_style", "skip_hidden"):
            if flag in data and type(data[flag]) is not bool:
                raise ValueError("boolean switch required")
        for flag in ("cell_limit", "max_chars"):
            if flag in data and (type(data[flag]) is not int or data[flag] < 1):
                raise ValueError("positive integer limit required")
        requested = data.get("ranges")
        if not isinstance(requested, list) or not requested or len(requested) > 100:
            raise ValueError("bounded nonempty ranges required")
        selections = [original._columns(region) for region in requested]
        remaining_cells, remaining_chars = data.get("cell_limit", 1000000000), data.get("max_chars", 500000)
        ranges, coordinates, hashes, formulas = [], [], {}, []
        partial = False
        for region, columns in zip(requested, selections):
            row, returned = [], []
            for column in columns:
                cell = _render(self.current["cells"][0][ord(column) - ord("A")], mode)
                if data.get("include_styles") or data.get("include_conditional_format_style"):
                    # Explicit synthetic default, matching the observed private sample.
                    cell["cell_styles"] = {"font_size": 13, "vertical_alignment": "middle"}
                if data.get("include_truncation_info"):
                    cell.update(isRowTruncated=False, isColTruncated=False)
                size = len(json.dumps(cell, ensure_ascii=False))
                if remaining_cells < 1 or remaining_chars < size:
                    break
                remaining_cells -= 1
                remaining_chars -= size
                row.append(cell)
                returned.append(column)
                coordinate = column + "1"
                coordinates.append(coordinate)
                hashes[coordinate] = _content_hash(cell)
                if "formula" in cell:
                    formulas.append(coordinate)
            truncated = len(returned) != len(columns)
            partial |= truncated
            ranges.append({"range": region, "actual_range": original._extent(returned) if returned else "",
                           "row_indices": [1] if returned else [], "col_indices": returned,
                           "truncated": truncated, "cells": [row] if returned else []})
        revision = self.current["revision"]
        output = {"spreadsheet_token": SOURCE["spreadsheet_token"], "sheet_id": SOURCE["sheet_id"],
                  "revision": revision, "has_more": partial, "returned_cell_count": len(coordinates), "ranges": ranges}
        proof = {"operation": "get_cell_ranges", "spreadsheet_token": SOURCE["spreadsheet_token"],
                 "sheet_id": SOURCE["sheet_id"], "identity": "user", "coordinates": coordinates,
                 "render": mode, "revision": revision, "content_hashes": hashes,
                 "formula_coordinates": formulas}
        return output, proof


def verify(workspace, answer, receipt, expected):
    """Require independent signed typed reads before validating actual artifact bytes."""
    try:
        if receipt.get("scenario") != SCENARIO:
            return False
        raw_seen, formula_seen = set(), set()
        for record in receipt.get("requests", []):
            if original._mutation(record.get("method", "GET"), record.get("uri", "")):
                return False
            if record.get("route") == "identity" and record.get("status") == 200:
                if record.get("signature_valid") is not True or record.get("method") != "GET" or record.get("uri") != "/open-apis/authen/v1/user_info":
                    return False
            if record.get("route") != "sheets_cells_read" or record.get("status") != 200:
                continue
            proof = record.get("proof", {})
            if record.get("signature_valid") is not True or record.get("method") != "POST" or record.get("uri") != READ_PATH:
                return False
            if (proof.get("operation") != "get_cell_ranges" or proof.get("identity") != "user"
                    or proof.get("spreadsheet_token") != expected["source"]["spreadsheet_token"]
                    or proof.get("sheet_id") != expected["source"]["sheet_id"]):
                return False
            if type(proof.get("revision")) is not int or proof["revision"] != expected["source"]["revision"]:
                return False
            mode, coordinates = proof.get("render"), proof.get("coordinates")
            if mode not in ("raw_value", "formula") or not isinstance(coordinates, list) or not set(coordinates) <= COORDS:
                return False
            hashes = proof.get("content_hashes")
            if not isinstance(hashes, dict) or set(hashes) != set(coordinates):
                return False
            explicit = []
            for coordinate in coordinates:
                cell = expected["rendered"][mode][coordinate]
                if hashes[coordinate] != _content_hash(cell):
                    return False
                if "formula" in cell:
                    explicit.append(coordinate)
            if proof.get("formula_coordinates") != explicit:
                return False
            if mode == "raw_value":
                raw_seen.update(coordinates)
            else:
                formula_seen.update(explicit)
        if raw_seen != COORDS or formula_seen != {"E1"}:
            return False
        state = receipt.get("state", {})
        if not original._same(state.get("initial"), expected["source"]) or not original._same(state.get("final"), expected["source"]) or type(state.get("mutation_attempts")) is not int or state["mutation_attempts"] != 0:
            return False
        if not isinstance(answer, dict) or set(answer) != {"artifact_path"}:
            return False
        relative = answer["artifact_path"]
        if not isinstance(relative, str) or not relative or Path(relative).is_absolute():
            return False
        root = Path(workspace).resolve()
        path = (root / relative).resolve(strict=True)
        if not path.is_relative_to(root) or not path.is_file() or path.stat().st_size > 1000000:
            return False
        artifact = original._json(path.read_text(encoding="utf-8"))
        if not isinstance(artifact, dict):
            return False
        if artifact.get("schema") == "feishu-cli-next/result/v1":
            payload = original._bound_payload(artifact, receipt["requests"], expected["binding"])
        elif "schema" in artifact:
            return False
        elif "ok" in artifact:
            if artifact["ok"] is not True:
                return False
            payload = artifact.get("data")
        else:
            payload = artifact
        cells = original._native_cells(payload)
        for column, wanted in zip("ABCD", expected["source"]["cells"][0][:4]):
            cell = cells[column + "1"]
            if "value" not in cell or not original._cell_value_same(cell["value"], wanted["value"]) or cell.get("formula") not in (None, ""):
                return False
        formula = cells["E1"]
        return formula.get("formula") == "=A1+1" and "value" in formula and original._cell_value_same(formula["value"], 1)
    except (OSError, UnicodeError, ValueError, TypeError, KeyError, AttributeError):
        return False
